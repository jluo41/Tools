    U.text(0, 50, "One row per Space: its views side by side, each a full screen with its files under it; the Space "
                  "explained on the right. ◆ = what the paper adds; red = proposed or open; green ✎ = a change, dated. Placeholders only.", 20, GRAY)
    for k, (a, b) in enumerate(MOVES):
        U.text(0, 120 + k * 32, a, 17, GRAY)
        U.text(460, 120 + k * 32, "→  " + b, 17, RED if "?" in b else INK)
