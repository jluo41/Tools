def about(x, y, items):
    """The Space explained, on the right of its row: a heading, then lines (◆ paper adds, ? open = red)."""
    for kind, s in items:
        if kind == "h":
            U.text(x, y, s, 24)
            y += 50
            continue
        color = {"◆": TEAL, "?": RED, "✎": GREEN}.get(kind, INK)
        lead = {"◆": "◆ ", "?": "? ", "✎": "✎ 261007  "}.get(kind, "")
        for k, line in enumerate(U.wrap(lead + s, 70)):
            U.text(x, y + k * 28, line, 18, color)
        y += len(U.wrap(lead + s, 70)) * 28 + 18
    return y


def level_rows(out):
    """One row per Space (JL 261007: "make each space to be a row"): its views side by side, each a full
    screen with "on disk" under it, and the Space explained on the right; one frame per row."""
    L = U.L
