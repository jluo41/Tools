def run_cards(cx, cy, cw, lane, pills, groups):
    x = cx
    for t in LANES:                                   # the lane tabs, inside the view (no third row)
        w = 24 + 9 * len(t)
        U.base("rectangle", x, cy, w, 30, INK if t == lane else GRAY, 1.5 if t == lane else 1, rough=0)
        U.text(x + 12, cy + 6, t, 14, INK if t == lane else GRAY)
        x += w + 8
    U.path([(cx, cy + 40), (cx + cw, cy + 40)], arrow=False, color=GRAY)
    cy, x = cy + 54, cx
    for k, (label, n) in enumerate(pills):
        w = 14 + 9 * len(f"{n} {label}")
        U.base("rectangle", x, cy, w, 26, GRAY, 1, rough=0)
        U.text(x + 8, cy + 4, f"{n} {label}", 13, INK if k == 0 else GRAY)
        x += w + 8
    y = cy + 44
    for name, runs in groups:
        U.text(cx, y, name, 15, GRAY)
        y += 26
        if not runs:
            U.base("rectangle", cx, y, cw, 36, GRAY, 1, dashed=True, rough=0)
            U.text(cx + 12, y + 9, f"No {name} Run yet.", 13, GRAY)
            y += 48
        for title, state, action, file in runs:
            U.base("rectangle", cx, y, cw, 62, GRAY, 1, rough=0)
            U.text(cx + 12, y + 8, title, 15, INK)
            U.text(cx + 12, y + 34, action, 13, GRAY)
            U.text(cx + cw - 300, y + 34, file, 12, GRAY, MONO)
            U.text(cx + cw - 90, y + 8, "● " + state, 13, GRAY if state == "closed" else INK)
            U.text(cx + cw - 22, y + 18, "›", 20, GRAY)
            y += 70
        y += 8
    return y


