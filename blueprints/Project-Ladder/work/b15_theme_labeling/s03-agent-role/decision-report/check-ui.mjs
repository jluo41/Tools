import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)('playwright');
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const url=pathToFileURL(path.join(root,'build/index.html')).href;
const browser=await chromium.launch({headless:true,channel:'chrome'});
try {
const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
const page=await context.newPage(), errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(url);
assert.equal(await page.locator('.card').count(),6);
assert.equal(await page.locator('input:checked').count(),0,'No default preference');
await page.screenshot({path:path.join(root,'build/desktop.png')});
await page.locator('#review').click();
assert.equal(await page.locator('#reviewDialog').evaluate(e=>e.open),false,'Empty submission blocked');
await page.locator('input[name="D01"][value="A"]').check();
await page.locator('input[name="D02"][value="none"]').check();
await page.locator('#review').click();
assert.match(await page.locator('#error-D02').innerText(),/describe your alternative/);
await page.locator('#comment-D02').fill('Use a separate tone label. <img src=x onerror=alert(1)>');
await page.locator('input[name="D03"][value="defer"]').check();
await page.locator('#comment-D03').fill('Please bring more contrastive examples.');
await page.locator('#save').click();
await page.reload();
assert.equal(await page.locator('input[name="D01"][value="A"]').isChecked(),true,'Draft restored');
assert.match(await page.locator('#comment-D02').inputValue(),/separate tone/);
await page.locator('#review').click();
assert.equal(await page.locator('#reviewDialog').evaluate(e=>e.open),true);
assert.equal(await page.locator('#reviewList img').count(),0,'Comments rendered as text');
const downloadPromise=page.waitForEvent('download');
await page.locator('#submit').click();
const download=await downloadPromise;
const file=path.join(root,'build/test-feedback.json');
await download.saveAs(file);
const feedback=JSON.parse(await fs.readFile(file,'utf8'));
assert.equal(feedback.item_labels_approved,false);
assert.equal(feedback.decisions[0].status,'confirmed_preference');
assert.equal(feedback.decisions[1].status,'custom_proposal');
assert.equal(feedback.decisions[2].status,'deferred');
assert.equal(feedback.decisions[3].status,'unanswered');
assert.equal(feedback.base_guideline_version,'G0-demo');
assert.equal(feedback.decisions[0].approval_scope,'rule_preference_only');
assert.deepEqual(feedback.decisions[0].learning_item_ids,['L01','L02']);
assert.equal(await page.locator('#receipt').isVisible(),true);
await page.locator('input[name="D01"][value="B"]').check();
assert.equal(await page.locator('#receipt').isVisible(),false,'Editing clears stale receipt');
await page.locator('#D01').scrollIntoViewIfNeeded();
await page.evaluate(()=>window.scrollTo(0,document.getElementById('D01').offsetTop-100));
await page.screenshot({path:path.join(root,'build/decision-card.png')});
const mobile=await browser.newContext({viewport:{width:390,height:844}});
const m=await mobile.newPage();await m.goto(url);
assert.equal(await m.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Mobile width fits');
await m.locator('input[name="D01"][value="C"]').check();
await m.screenshot({path:path.join(root,'build/mobile.png')});
const blocked=await browser.newContext();
await blocked.addInitScript(()=>{Storage.prototype.setItem=function(){throw new Error('Storage unavailable');};});
const b=await blocked.newPage();await b.goto(url);
await b.locator('input[name="D01"][value="A"]').check();
assert.match(await b.locator('#saveStatus').innerText(),/Could not save/);
assert.deepEqual(errors,[]);
console.log('PASS: empty defaults, validation, draft restore, safe comments, review, JSON export, partial/deferred states, provenance, edited-receipt invalidation, mobile layout, storage failure.');
} finally {await browser.close();}
