"""Carry a register board over to plan C's levels (b11 s11 · s12 · s13): one Job, one Task per question.

    python carry_today.py <insights/<board>>          # writes the folders, then prints what it wrote
    python carry_today.py <insights/<board>> --check  # prints what it would write, writes nothing

It writes pointers only, never a copy: `j01_p1_<dataset><vM>/j01_p1_<dataset><vM>.md` (`carried: today`, the
release and the data version) and, per registered question, `tNN_<L><NN>_<slug>/tNN_<L><NN>_<slug>.md`
(`carried: today`, `question: Q<L><N>`). Every answer, run and page stays where it is; insight_carry.py
reads them live. Rerunning it rewrites the same faces and adds a Task for a newly registered question.
Generated: never hand-edit what it writes.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "_host"))
from host_paths import bootstrap  # noqa: E402
bootstrap()
from live import insight_carry as C  # noqa: E402
from live import insightboard as IB  # noqa: E402

HEAD = "<!-- generated by servers/workbench-insight/carry_today.py; do not hand-edit -->\n"


def plan(block: Path) -> dict:
    """{relative path: text} of every face to write."""
    snap = C.snapshot(block)
    dataset, version, *_ = C.dataset_version(snap)
    job = f"j01_p1_{dataset}{version}"
    out = {f"{job}/{job}.md": (f"---\ncarried: today\nrelease: p1\ndata: {version}\nstate: open\nmoved: start\n---\n{HEAD}"
                               f"# {job}\n\nToday's questions (release p1) on {dataset} {version}: the one Job of a register "
                               "board, carried over. Its answers stay in the partition folders.\n")}
    notes = IB.question_notes(snap)
    for k, q in enumerate(snap["questions"], 1):
        name = f"t{k:02d}_{C.qid(q['id'])}_{C.slug(notes.get(q['id'], {}).get('name') or q['question'])}"
        out[f"{job}/{name}/{name}.md"] = (f"---\ncarried: today\nquestion: {q['id']}\n---\n{HEAD}# {name}\n\n"
                                          f"{q['question']}\n")
    return out


def main(argv: list) -> int:
    if not argv:
        print(__doc__)
        return 2
    block = Path(argv[0]).resolve()
    faces = plan(block)
    for relpath, text in faces.items():
        path = block / relpath
        if "--check" not in argv:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        print(("would write " if "--check" in argv else "wrote ") + relpath)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
