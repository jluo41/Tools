"""A display unit's preview.pdf: page 1 the display as a reader sees it (its float.tex: the figure or table, its caption
and label), pages 2 and on what it says and how it was made, from method.md beside it (JL 261101: "I want to make the preview the first
page to be the display and content, could you make the second page and beyond to be things like the methods, to
explain how this display is generated?").

    python build_preview.py <unit folder>          writes <unit>/preview.tex, compiles <unit>/preview.pdf
    python build_preview.py <unit folder> --look paper   page 1 in the paper's default look (12pt Times, 1.5 spacing,
                                                   the page number below), as haipipe-paper-assemble prints it
    python build_preview.py <unit folder> --preamble-from <delivery/<job>/latex/master.tex>
                                                   page 1 exactly as that built paper prints it: the paper's own
                                                   head (its fonts, caption style, preamble.tex, header), endfloat
                                                   dropped so the display stays on page 1 (JL 261101: "the full
                                                   pdf preview, just like the one we will see in the paper pdf")
    python build_preview.py <unit folder> --method-from <source preview.pdf>
                                                   a writing Job's unit (the paper's Figure 1, framed): page 1 its own
                                                   float, then the source version's method pages (its pages 2 on), so
                                                   the method is written once, with the version that drew it

The unit is any folder that holds float.tex (a Section's display/Display<n>-<slug>/, or a display Run's result/).
method.md is Markdown the display's maker writes, one heading per part:

    ## Message       what we want to say with this display, in one to three sentences: the finding the reader should
                     leave with (JL 261103: "the first section should be: what we want to say with this display"); it
                     opens page 2 as "What this display says", before "How this display was made"
    ## Data          what the numbers come from (sources, years)
    ## Sample        who is in it, and how they were chosen
    ## Method        the matching, the model, the estimator
    ## Outcomes      each outcome, as it is defined
    ## Made by       the Runs that produced it, by path
    ## Numbers       read from Result files, or screen readings still to return

A unit with no method.md gets a page 2 that says so, so the gap shows. The preamble is the unit's own: kept from an
existing preview.tex (everything before \\begin{document}, which is the unit's dependency declaration, haipipe-display
_parts/tex/PART.md), else a plain one. preview.tex is written by this script; never edit it by hand, rerun it.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

PLAIN = r"""\documentclass[11pt]{article}
\usepackage[letterpaper,margin=1in]{geometry}
\usepackage{graphicx,booktabs,tabularx,multirow,array,longtable,float,caption,amsmath,amssymb,xcolor}
\usepackage[T1]{fontenc}
"""
# the paper's default head, as haipipe-paper-assemble build_delivery.write_master writes it before a paper has a
# built master.tex of its own; a built master.tex (--preamble-from) always wins
PAPER = r"""\documentclass[12pt]{article}
\usepackage[letterpaper,margin=1in]{geometry}
\usepackage{fontspec}
\IfFontExistsTF{TeX Gyre Termes}{\setmainfont{TeX Gyre Termes}}{\IfFontExistsTF{Times New Roman}{\setmainfont{Times New Roman}}{}}
\usepackage{microtype}
\usepackage{graphicx,booktabs,tabularx,multirow,array,longtable,amsmath,amssymb,setspace,caption,float,xcolor}
\usepackage{fancyhdr}
\onehalfspacing
\setlength{\parindent}{0.25in}
\setlength{\parskip}{0.35em}
\pagestyle{fancy}\fancyhf{}
\renewcommand{\headrulewidth}{0pt}
\fancyfoot[C]{\thepage}
"""
MARK = "% GENERATED by haipipe-display scripts/build_preview.py: page 1 the display, pages 2+ how it was made. Rerun it."


def tex(s: str) -> str:
    """Plain text made safe for LaTeX; `code` becomes \\texttt, **bold** becomes \\textbf."""
    parts = re.split(r"(`[^`]+`|\*\*[^*]+\*\*)", s)
    out = []
    for p in parts:
        body = p[1:-1] if p.startswith("`") else p[2:-2] if p.startswith("**") else p
        body = (body.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%").replace("$", r"\$")
                .replace("#", r"\#").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}")
                .replace("~", r"\textasciitilde{}").replace("^", r"\^{}"))
        out.append(rf"\texttt{{{body}}}" if p.startswith("`") else rf"\textbf{{{body}}}" if p.startswith("**") else body)
    return "".join(out)


def method_tex(md: str) -> str:
    """method.md as LaTeX: ## headings, paragraphs, - and 1. lists."""
    out, items, kind = [], [], ""

    def flush():
        nonlocal items, kind
        if items:
            env = "enumerate" if kind == "ol" else "itemize"
            out.append(rf"\begin{{{env}}}" + "".join(rf"\item {tex(i)}" + "\n" for i in items) + rf"\end{{{env}}}")
        items, kind = [], ""

    para = []
    for line in md.splitlines() + [""]:
        s = line.strip()
        m_h = re.match(r"^#{1,4}\s+(.+)$", s)
        m_ul = re.match(r"^[-*]\s+(.+)$", s)
        m_ol = re.match(r"^\d+[.)]\s+(.+)$", s)
        if m_h or m_ul or m_ol or not s:
            if para:
                out.append(tex(" ".join(para)) + "\n")
                para = []
        if m_h:
            flush()
            out.append(rf"\subsection*{{{tex(m_h.group(1))}}}")
        elif m_ul or m_ol:
            k = "ul" if m_ul else "ol"
            if kind and kind != k:
                flush()
            kind = k
            items.append((m_ul or m_ol).group(1))
        elif not s:
            flush()
        else:
            flush()
            para.append(s)
    flush()
    return "\n".join(out)


def paper_head(master: Path) -> str:
    """A built paper's master.tex, up to \\begin{document}, as a display's preamble: its generated-file notes, its
    title lines and endfloat (which would move the display to the end) are dropped; everything else stays."""
    head = master.read_text(encoding="utf-8", errors="ignore").split(r"\begin{document}")[0]
    keep = [ln for ln in head.splitlines()
            if not re.match(r"\s*(% GENERATED|% The pages own|\\title\{|\\author\{|\\date\{)", ln)
            and "{endfloat}" not in ln]
    return "\n".join(keep).strip() + "\n"


NUMBERED = re.compile(r"^\s*(e|Extended Data |Supplementary |Appendix )?(Figure|Table)\s+([A-Za-z]?\d+[a-z]?)\b")


def numbering(unit: Path) -> str:
    """The float's printed name and number, as TeX, so page 1 reads "Figure 3" or "eTable 11", never "Figure 1"
    (pp-LBP-JAMA 261103): a writing Job unit's README `number:`; else, for a Run's result/, its display Task face's
    `number:` then `label:`. A Supplement display keeps its e (eFigure, eTable); a lettered number (Table B1) prints
    as written. Nothing found: LaTeX's own count."""
    fields = []
    if (unit / "README.md").is_file():
        fields.append(unit / "README.md")
    if unit.name == "result" and unit.parent.parent.name == "runs":
        task = unit.parent.parent.parent
        fields.append(task / f"{task.name}.md")
    for f in fields:
        if not f.is_file():
            continue
        text = f.read_text(encoding="utf-8", errors="ignore")
        for key in ("number", "label"):
            m = re.search(rf"(?m)^{key}:\s*(.+)$", text)
            n = NUMBERED.match(m.group(1)) if m else None
            if n:
                pre, num = (n.group(1) or ""), n.group(3)
                return (f"\\renewcommand{{\\figurename}}{{{pre}Figure}}\\renewcommand{{\\tablename}}{{{pre}Table}}"
                        f"\\renewcommand{{\\thefigure}}{{{num}}}\\renewcommand{{\\thetable}}{{{num}}}\n")
    return ""


def earlier_tex(unit: Path, earlier: list[dict]) -> str:
    """After the method pages: one page per earlier version, its display page only (its page 1), newest first. Each
    item holds pdf, name, date, note. The line before them records where the method pages end, for --method-from."""
    out = "\\clearpage\n\\typeout{PREVIEW-METHOD-PAGES=\\the\\numexpr\\value{page}-1\\relax}\n"
    for e in earlier:
        rel = Path(__import__("os").path.relpath(Path(e["pdf"]).resolve(), unit)).as_posix()
        out += (f"\\section*{{Earlier version: {tex(e['name'])}}}\n{{\\small {tex(e.get('date', ''))}"
                + (f": {tex(e['note'])}" if e.get("note") else "") + "\\par}\n\\medskip\n"
                f"\\begin{{center}}\\includegraphics[page=1,width=\\linewidth,height=0.8\\textheight,keepaspectratio]{{{rel}}}\\end{{center}}\n\\clearpage\n")
    return out


def method_range(src: Path) -> str:
    """Pages of a source preview that hold its method: its pages 2 on, without its earlier versions."""
    side = src.with_name("preview-method-pages.txt")
    last = side.read_text().strip() if side.is_file() else ""
    return f"2-{last}" if last.isdigit() else "2-"


def build(unit: Path, method_from: Path | None = None, look: str = "", preamble_from: Path | None = None,
          earlier: list[dict] | None = None) -> Path:
    unit = unit.resolve()
    if not (unit / "float.tex").is_file():
        sys.exit(f"stop: {unit} has no float.tex (the display with its caption)")
    old = unit / "preview.tex"
    preamble = PLAIN
    if preamble_from is not None:
        if not preamble_from.is_file():
            sys.exit(f"stop: {preamble_from} does not exist (build the paper first, or pass --look paper)")
        preamble = paper_head(preamble_from.resolve())
    elif look == "paper":
        preamble = PAPER
    elif old.is_file():
        head = old.read_text(encoding="utf-8", errors="ignore").split(r"\begin{document}")[0]
        head = head.replace(MARK, "").strip()
        if r"\documentclass" in head:
            preamble = head + "\n"
    if r"\usepackage{float}" not in preamble and "float" not in re.findall(r"\\usepackage(?:\[[^]]*\])?\{([^}]*)\}", preamble):
        preamble += r"\usepackage{float}" + "\n"
    if earlier and "graphicx" not in preamble:
        preamble += r"\usepackage{graphicx}" + "\n"
    tail = earlier_tex(unit, earlier) if earlier else ""
    method = unit / "method.md"
    if method_from is not None:                    # the source version's method pages, as they are
        src = method_from.resolve()
        if not src.is_file():
            sys.exit(f"stop: {src} does not exist")
        if "pdfpages" not in preamble:
            preamble += r"\usepackage{pdfpages}" + "\n"
        rel = Path(__import__("os").path.relpath(src, unit)).as_posix()
        body = (MARK + "\n" + preamble + "\\begin{document}\n" + _style(preamble) +
                "\\makeatletter\\renewcommand{\\fps@figure}{H}\\renewcommand{\\fps@table}{H}\\makeatother\n" + numbering(unit) +
                f"\\input{{float.tex}}\n\\clearpage\n\\includepdf[pages={method_range(src)}]{{{rel}}}\n{tail}\\end{{document}}\n")
        return _compile(unit, old, body)
    text = re.sub(r"\A#\s+[^\n]*\n", "", method.read_text(encoding="utf-8", errors="ignore")) if method.is_file() else ""
    said = re.search(r"(?ms)^##\s*Message\s*\n(.*?)(?=^##\s|\Z)", text)   # the Message part opens page 2 on its own
    text = (text[:said.start()] + text[said.end():]) if said else text
    says = (method_tex(said.group(1).strip()) if said and said.group(1).strip() else
            r"\emph{No message written yet: add a ``\#\# Message'' part to method.md (what we want to say with this "
            r"display), then rerun build\_preview.py.}")
    how = (method_tex(text) if method.is_file() else r"\emph{No method written yet: write method.md beside float.tex "
           r"(Message, Data, Sample, Method, Outcomes, Made by, Numbers), then rerun build\_preview.py.}")
    body = (MARK + "\n" + preamble + "\\begin{document}\n" + _style(preamble) +
            "\\makeatletter\\renewcommand{\\fps@figure}{H}\\renewcommand{\\fps@table}{H}\\makeatother\n" + numbering(unit) +   # page 1 holds it
            "\\input{float.tex}\n\\clearpage\n" + ("" if "fancyhdr" in preamble else "\\pagestyle{plain}\n") +
            "\\section*{What this display says}\n" + says + "\n\\section*{How this display was made}\n" + how +
            "\n" + tail + "\\end{document}\n")
    return _compile(unit, old, body)


def _style(preamble: str) -> str:
    """A paper head keeps its own page style (header, page number), as the paper prints; a plain one has none."""
    return "" if "fancyhdr" in preamble else "\\pagestyle{empty}\n"


def _compile(unit: Path, old: Path, body: str) -> Path:
    old.write_text(body, encoding="utf-8")
    engine = "xelatex" if shutil.which("xelatex") else "pdflatex"
    if "fontspec" in body and engine == "pdflatex":
        sys.exit("stop: the paper look loads fontspec, which needs xelatex; install it or pass no --look")
    for _ in range(2):
        r = subprocess.run([engine, "-interaction=nonstopmode", "-halt-on-error", "preview.tex"], cwd=unit,
                           capture_output=True, text=True)
    if r.returncode != 0 or not (unit / "preview.pdf").is_file():
        sys.exit("stop: the preview did not compile:\n" + "\n".join(r.stdout.splitlines()[-20:]))
    pages = re.search(r"PREVIEW-METHOD-PAGES=(\d+)", r.stdout)
    side = unit / "preview-method-pages.txt"
    if pages:
        side.write_text(pages.group(1) + "\n")
    else:
        side.unlink(missing_ok=True)
    for ext in (".aux", ".log", ".out"):
        (unit / f"preview{ext}").unlink(missing_ok=True)
    return unit / "preview.pdf"


if __name__ == "__main__":
    args = sys.argv[1:]
    opt = {}
    for flag in ("--method-from", "--look", "--preamble-from"):
        if flag in args:
            i = args.index(flag)
            opt[flag] = args[i + 1] if i + 1 < len(args) else sys.exit(__doc__)
            del args[i:i + 2]
    if len(args) != 1 or opt.get("--look", "paper") not in ("paper", "plain"):
        sys.exit(__doc__)
    src = Path(opt["--method-from"]) if "--method-from" in opt else None
    pre = Path(opt["--preamble-from"]) if "--preamble-from" in opt else None
    print(build(Path(args[0]), src, opt.get("--look", ""), pre))
