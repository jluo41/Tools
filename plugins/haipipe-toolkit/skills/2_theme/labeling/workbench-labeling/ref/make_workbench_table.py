"""Write workbench-table.md, the Labeling Workbench Table, from ref-space-mapping.md.

The table (skills/0_utils/table-workbench in haipipe-toolkit: Level · Space · View · Run
type · Agent · Skill · Person signs) is generated, never edited by hand. Its facts live in
`haipipe-labeling-building/ref/ref-space-mapping.md`:

    Space roster                   the Spaces and their Views, in order
    Corpus Preparation Run Types   Data › Preparation: Run type, words and Skill
    Run Type skills                every other Run type's declared Skills (the last is the View's)
    Run Type agents                the agent and what the person signs, for every Run type
    Workflow map                   the words and the one View that lists each Run type

Change a row there, then run

    .venv/bin/python Tools/plugins/haipipe-toolkit/skills/2_theme/labeling/workbench-labeling/ref/make_workbench_table.py

and check the result with table-workbench's `render_workbench_table.py --check`.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / "haipipe-labeling-building" / "ref" / "ref-space-mapping.md"   # ref -> workbench-labeling -> labeling
OUT = HERE / "workbench-table.md"

HEAD = """Labeling Workbench Table
========================

Generated by `make_workbench_table.py` beside this file from
`haipipe-labeling-building/ref/ref-space-mapping.md`; do not edit it by hand. Shape and check:
haipipe-toolkit `skills/0_utils/table-workbench/SKILL.md`.

Rows run input → process → output: the Guide and the Board's list of jobs, then the
Page's four Spaces in order (Data, Labeling, Quality, Delivery), each View's Run types in
step order. A Run type's Skill is the last of its declared Skills, the one for its View;
the shared ones before it (`haipipe-labeling-workflow`, `haipipe-labeling-building`, ...) route and
gate. The agent prepares the Run and calls the engine's checked writer, which still owns
execution and authorization; the person never does a Run and signs only what is theirs.
Most Run types after round 1 have no worker yet (`not built yet` in the Workflow map):
their rows plan who will do them. `(new)` marks an agent or skill planned but not written.

"""

GUIDE = [
    ("board", "Guide", "Description", "none", "none", "none", "none"),
    ("board", "Guide", "Method", "none", "none", "none", "none"),
    ("board", "Guide", "RoadMap Draw", "Redraw the Workbench design", "haipipe-studio-agent (new)",
     "workbench-labeling", "none"),
    ("board", "Guide", "Related Paper", "Add a paper", "haipipe-discovery-orchestrator-agent",
     "haipipe-discovery", "the source check"),
    ("board", "Jobs", "Jobs", "none", "none", "none", "none"),
]


def table(text: str, heading: str) -> list[dict[str, str]]:
    """The first Markdown table under `## heading`, as rows keyed by lower-case header."""
    match = re.search(r"^## %s\s*$" % re.escape(heading), text, re.M)
    if not match:
        raise SystemExit("ref-space-mapping.md has no `## %s`" % heading)
    lines = []
    for line in text[match.end():].split("\n## ", 1)[0].splitlines():
        if line.startswith("|"):
            lines.append(line)
        elif lines:
            break                       # only the first table of the section
    header = [c.strip().lower() for c in lines[0].strip("|").split("|")]
    return [dict(zip(header, (c.strip() for c in line.strip("|").split("|")))) for line in lines[2:]]


def code(cell: str) -> str:
    return cell.strip().strip("`")


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    roster = table(text, "Space roster")
    agents = {code(r["run type"]): r for r in table(text, "Run Type agents")}
    skills = {code(r["run type"]): re.findall(r"`([^`]+)`", r["declared skills"])
              for r in table(text, "Run Type skills")}
    by_view: dict[tuple[str, str], list[tuple[str, str, str]]] = {}
    for r in table(text, "Corpus Preparation Run Types"):
        by_view.setdefault(("Data", "Preparation"), []).append(("0." + r["step"], code(r["run type"]), r["in words"]))
    for r in table(text, "Workflow map"):
        space, _, view = r["view"].partition(" · ")
        by_view.setdefault((space.strip(), view.strip()), []).append((r["step"], code(r["run type"]), r["in words"]))
        if not skills.get(code(r["run type"])):
            raise SystemExit("`%s` has no declared Skills" % code(r["run type"]))
    prep_skill = {code(r["run type"]): code(r["skill"]) for r in table(text, "Corpus Preparation Run Types")}

    rows = list(GUIDE)
    missing = []
    for space_row in roster:
        space = space_row["space"].strip("* ")
        for view in (v.strip() for v in space_row["views"].split("·")):
            types = sorted(by_view.pop((space, view), []), key=lambda t: float(t[0]))
            if not types:
                rows.append(("page", space, view, "none", "none", "none", "none"))
            for _, op, words in types:
                who = agents.get(op)
                if not who:
                    missing.append(op)
                    continue
                skill = prep_skill.get(op) or skills[op][-1]
                rows.append(("page", space, view, words, who["agent"], skill, who["person signs"]))
    if missing or by_view:
        raise SystemExit("not placed: agents missing for %s; views not in the roster: %s"
                         % (missing, sorted(by_view)))
    body = ["| Level | Space | View | Run type | Agent | Skill | Person signs |",
            "|---|---|---|---|---|---|---|"]
    body += ["| %s |" % " | ".join(row) for row in rows]
    OUT.write_text(HEAD + "\n".join(body) + "\n", encoding="utf-8")
    print("wrote %s · %d rows" % (OUT.name, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
