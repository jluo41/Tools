"""The paper checklist as its Studio topic shows it (sNN-paper-checklist/, read on the workbench): paper_check.py's
rows, one line per item, with no tally. A check's counts ("1 of 2 Sections", "3 of 5 Tasks", "N of M done") stay in
the checker's own report (its printout and --json); on the page each item's mark carries its state and what it saw
(the Sections off, the names missing) is where the finding lands (AGENTS.md § Page words)."""
from __future__ import annotations

import re

GENERATED = ("<!-- GENERATED by haipipe-paper scripts/paper_check.py --write: the checklist ticked from the Board's own "
             "files. Rerun it; never edit below this line. -->")
LAYERS = {"layout": "⓪ Layout", "plan": "① Plan", "explore": "② Explore", "evidence": "③ Evidence", "writing": "④ Writing",
          "delivery": "⑤ Delivery"}
TALLY = re.compile(r"\b\d+ of \d+\b[^;]*(?:;\s*|$)")


def untallied(seen: str) -> str:
    """What an item saw, its "N of M ..." phrase dropped: "1 of 2 Sections; off: t02_results (C1.P2)" reads
    "off: t02_results (C1.P2)", and "2 of 5 Sections signed" reads nothing (the mark says it)."""
    return TALLY.sub("", seen or "").strip(" ;")


def lines(rows: list) -> str:
    """The checklist as Markdown: a heading per layer, one line per item, its mark first and no tally."""
    out, last = [], ""
    for layer, i, what, m, seen in rows:
        if layer != last:
            out += ["", f"### {LAYERS[layer]}", ""]
            last = layer
        said = untallied(seen)
        out.append(f"- {m} **{i} · {what}**" + (f": {said}" if said else ""))
    return "\n".join(out).strip() + "\n"
