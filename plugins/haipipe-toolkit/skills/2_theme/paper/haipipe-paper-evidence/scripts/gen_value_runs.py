"""gen_value_runs.py · a paper's value Job made from its value maps: each value Task's Run, and the paper-wide check.

    python gen_value_runs.py <paper>/j02_evidence_value [--started-by "<who and why>"]

A paper's `j02_evidence_value` holds only value maps, `tNN_<group>/scripts/value_map.yaml` (values_ledger.py says
the format). This writes, for each Task with a map, its one Run, `runs/r01_collect_values/` (run.yaml and the ticket
r01_collect_values.sh, which runs `values_ledger.py run`), and the paper-wide Task `t99_paper_value_check/` (its face,
and `runs/r01_check_values/`, which runs `values_ledger.py check`). A value Task's face is written only when it has
none; a face this script wrote says GENERATED and is rewritten. It never runs a ticket. Rerun it after a map gains or
loses a Run; never edit a card or a ticket by hand.

The ticket finds the toolkit (`Tools/plugins/haipipe-toolkit` or `plugins/haipipe-toolkit`) and a Python (the
`HAIPIPE_PYTHON` variable, else the nearest `.venv/bin/python`, else python3) by walking up from its Run folder, so the
same ticket runs in any SPACE.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_text as pt  # noqa: E402
from values_ledger import CHECK_RUN, CHECK_TASK, RUN, _rel  # noqa: E402

GEN = "# GENERATED by haipipe-paper-evidence scripts/gen_value_runs.py; rerun it, never edit this file.\n"

TICKET = """#!/usr/bin/env bash
# GENERATED by haipipe-paper-evidence scripts/gen_value_runs.py; rerun it, never edit this file.
# {run} · {task}: {says}
# Reads returned, aggregated Results only (the value maps name each file and column); no model call, no raw data.
set -euo pipefail
RUN_DIR="$(cd "$(dirname "$0")" && pwd)"
TASK_DIR="$(cd "$RUN_DIR/../.." && pwd)"
RESULT_DIR="$RUN_DIR/result"
TK=""; PY="${{HAIPIPE_PYTHON:-}}"; D="$RUN_DIR"
while [ "$D" != "/" ]; do
  for c in "$D/Tools/plugins/haipipe-toolkit" "$D/plugins/haipipe-toolkit"; do
    [ -z "$TK" ] && [ -d "$c" ] && TK="$c"
  done
  [ -z "$PY" ] && [ -x "$D/.venv/bin/python" ] && PY="$D/.venv/bin/python"
  D="$(dirname "$D")"
done
[ -n "$TK" ] || {{ echo "haipipe-toolkit not found above $RUN_DIR" >&2; exit 2; }}
PY="${{PY:-$(command -v python3)}}"
rm -rf "$RESULT_DIR"
mkdir -p "$RESULT_DIR"
STARTED_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
set +e
"$PY" "$TK/skills/2_theme/paper/haipipe-paper-evidence/scripts/values_ledger.py" {cmd} "{target}" "$RESULT_DIR" 2>&1 | tee "$RESULT_DIR/0-{run}.log"
RC=${{PIPESTATUS[0]}}
set -e
cat > "$RESULT_DIR/runtime.yaml" <<EOT
run: {run}
status: $([ "$RC" = 0 ] && echo completed || echo failed)
exit_code: $RC
started_at: '$STARTED_AT'
finished_at: '$(date -u +%Y-%m-%dT%H:%M:%SZ)'
started_by: '{started_by}'
ticket: runs/{run}/{run}.sh
worker: haipipe-paper-evidence scripts/values_ledger.py {cmd}
host: $(hostname -s)/$(whoami)
EOT
exit "$RC"
"""


def write_run(task: Path, run: str, cmd: str, target: str, says: str, reads: list, started_by: str, root: Path) -> None:
    run_dir = task / "runs" / run
    run_dir.mkdir(parents=True, exist_ok=True)
    card = {"run": run, "kind": "hard", "role": "check" if cmd == "check" else "make", "type": "value",
            "scope": _rel(task, root), "ticket": f"{run}.sh",
            "worker": f"haipipe-paper-evidence scripts/values_ledger.py {cmd}", "says": says, "host": "this machine",
            "time": "a few seconds", "started_by": started_by, "reads": reads,
            "writes": ["result/values.yaml", "result/values.html", "result/ledger.csv", "result/headline.txt"]}
    (run_dir / "run.yaml").write_text(GEN + yaml.safe_dump(card, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    ticket = run_dir / f"{run}.sh"
    ticket.write_text(TICKET.format(run=run, task=task.name, says=says, cmd=cmd, target=target,
                                    started_by=started_by.replace("'", "’")), encoding="utf-8")
    ticket.chmod(0o755)
    print(f"wrote {task.name}/runs/{run}/ (run.yaml, {run}.sh)")


def face(task: Path, text: str) -> None:
    """A Task's face: written when missing, or rewritten when this script wrote it."""
    f = task / f"{task.name}.md"
    if f.is_file() and "GENERATED by haipipe-paper-evidence scripts/gen_value_runs.py" not in f.read_text(encoding="utf-8"):
        return
    f.write_text(text + f"\n<!-- {GEN.strip()[2:]} -->\n", encoding="utf-8")


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("job", type=Path, help="the paper Board's j02_evidence_value")
    ap.add_argument("--started-by", default="gen_value_runs.py: the value Job's Runs, made from its value maps")
    a = ap.parse_args(argv)
    job = a.job.resolve()
    root = pt.server_root(job)
    maps = [t for t in pt.tasks(job) if (t / "scripts" / "value_map.yaml").is_file()]
    if not maps:
        raise SystemExit(f"{job}: no tNN_/scripts/value_map.yaml; write a value map first (values_ledger.py says how)")
    for task in maps:
        vmap = yaml.safe_load((task / "scripts" / "value_map.yaml").read_text(encoding="utf-8")) or {}
        group = vmap.get("group", task.name)
        says = f"collect and check the printed numbers of {group}"
        write_run(task, RUN, "run", "$TASK_DIR", says, [f"{v} (result/)" for v in (vmap.get("runs") or {}).values()],
                  a.started_by, root)
        face(task, f"# {task.name} · {group}\n\nlabel: {(vmap.get('rq') + ' · ') if vmap.get('rq') else ''}{group}\n"
                   f"status: see runs/{RUN}/result/headline.txt\ntask-type: value\nfolder-kind: task\n"
                   f"reads: {', '.join((vmap.get('runs') or {}).values())}\n\n"
                   f"Every number the paper prints for {group}. `scripts/value_map.yaml` names each value's work Run; "
                   f"`runs/{RUN}/` reads them, checks each binding in the Sections and writes `result/values.html`.\n")
    check = job / CHECK_TASK
    write_run(check, CHECK_RUN, "check", "$(dirname \"$TASK_DIR\")",
              "check every printed number of the paper at once, and list the printed numbers with no binding",
              [f"{t.name}/scripts/value_map.yaml" for t in maps], a.started_by, root)
    face(check, f"# {CHECK_TASK} · every printed number at once\n\nlabel: Paper value check\n"
                f"status: see runs/{CHECK_RUN}/result/headline.txt\ntask-type: value\nfolder-kind: task\n"
                f"reads: the value maps of {', '.join(t.name for t in maps)}\n\n"
                "Every binding of every value Task checked at once (match, differs, missing, owed, pending, stale), the "
                "values never printed, and the numbers the text prints with no binding (candidates for an owed value).\n")


if __name__ == "__main__":
    main()
