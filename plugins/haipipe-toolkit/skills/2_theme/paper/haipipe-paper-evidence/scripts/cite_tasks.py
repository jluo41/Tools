"""cite_tasks.py · a paper's citations as the Tasks of its j03_evidence_cite: one Task per claim group, each checked
against its CITE evidence, and one paper-wide check.

    python cite_tasks.py gen       <paper>/j03_evidence_cite [--writing jNN_writing_v<MMDD>_<desk>]   faces, Run cards, tickets
    python cite_tasks.py run       <claim Task> <result dir>   one Task's Run (its ticket calls this)
    python cite_tasks.py inventory <paper>/j03_evidence_cite   every printed key, its group, its status
    python cite_tasks.py apply     <paper>/j03_evidence_cite   write the proposed CITE card edits into each Section (by hand)

A paper's j03 holds only its claim groups: `tNN_<group>/scripts/claim_group.yaml`:

    label: prescribing variation                  a few words for the Evidence list
    question: Do physicians decide differently for comparable patients?
    what: physician practice variation and the structural accounts of it
    discovery: b01.j01.t01                        where a missing source would be found (a need's proposal)
    keys: [Song_2022, barnett2017opioid]          the printed citation keys of the group
    writing: j11_writing_v1130_desk               optional: the writing Job (default: the Board's newest)

`gen` writes each group's Run, `runs/r01_check_citations/` (config.yaml, run.yaml, ticket), and the paper-wide Task
`t99_paper_citation_check/` (all keys at once; it also writes checks.md, proposed-cards/<section>.yaml and
proposals/<section>.md). A Task face is written when missing, or rewritten when this script wrote it. A printed key no
group holds is listed by `gen` and by t99, never dropped.

What a Run reads, all read only: each printed Section's text (paper_text.py: `## Content`, sentence ids from the draft's
`## 3 · Draft` or `<!-- realizes: -->`), its `\\citep`/`\\citet` keys; its `draft/evidence/bibex/*.bib`; the version's
built `delivery/<job>/latex/reference.bib`; its signed page-local CITE Results (`runs/run-citation-*/passes/*/result.yaml`:
`complete` with a passed human check or `verified: ✅ <person> <date>`), and CITE card items marked `verified: ✅ ...`;
its `evidence/cards.yaml` CITE items (resolved by haipipe-evidence cards.py to their discovery Run's one-entry .bib); the
Project's discovery bank (every `discovery/b*/j*/t*/runs/r*/result/*.bib`).

A key's status, in this order:
    TOADD        the text cites \\citep{TOADD}
    missing-bib  no printed Section's bib entry (bibex, or a CITE card's Run) holds the key, so it prints as "?"
    verified     a bib entry, and a person signed a CITE Result for it
    card-only    a bib entry and a CITE card or a discovery Run for it, not signed
    bib-only     a bib entry and nothing else
Also: keys with no DOI, one key with two DOIs across Sections, back-to-back sentences citing one key, citing sentences
with no CITE card, and the exact card edits (add, rebind, drop, need, cite-field). A Run writes only its result/:
citations.csv, citations.html, values.yaml, headline.txt. Only `apply`, run by a person, writes a Section's cards.yaml
(CITE items only; every VALUE item is kept as it is).
"""
