def parse_bib(text):
    """{key: {'type', 'fields'}} from BibTeX, brace-balanced (one-line Crossref entries too)."""
    out, i = {}, 0
    head = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,")
    while True:
        m = head.search(text, i)
        if not m:
            return out
        depth, j = 1, m.end()
        while j < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        body, fields, k = text[m.end():j - 1], {}, 0
        while True:
            f = re.compile(r"\s*,?\s*([A-Za-z_-]+)\s*=\s*").match(body, k)
            if not f:
                break
            k = f.end()
            if k < len(body) and body[k] == "{":
                d, s = 1, k + 1
                while s < len(body) and d:
                    d += {"{": 1, "}": -1}.get(body[s], 0)
                    s += 1
                val, k = body[k + 1:s - 1], s
            elif k < len(body) and body[k] == '"':
                e = body.index('"', k + 1)
                val, k = body[k + 1:e], e + 1
            else:
                e = re.compile(r"[^,]*").match(body, k).end()
                val, k = body[k:e].strip(), e
            fields[f[1].lower()] = val.strip()
        out.setdefault(m[2], {"type": m[1].lower(), "fields": fields})
        i = j


def norm_doi(d):
    return re.sub(r"^(https?://(dx\.)?doi\.org/|doi:)", "", (d or "").strip().lower())


def norm_title(t):
    return re.sub(r"[^a-z0-9]+", " ", re.sub(r"\\[a-z]+|[{}]", "", (t or "").lower())).strip()


def cards_module():
    spec = importlib.util.spec_from_file_location("cards", CARDS_PY)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sid_label(sid):
    return f"S{sid}" if re.fullmatch(r"\d+[a-z]*", str(sid)) else str(sid)


def text_of(sec):
    """[(sid, paragraph, text, keys)] of what the Section prints."""
    out = []
    for s in pt.printed(sec):
        keys = list(dict.fromkeys(k.strip() for g in CITE.findall(s["text"]) for k in g.split(",") if k.strip()))
        out.append((sid_label(s["id"]), s["para"], s["text"], keys))
    return out


def discovery_bank(project):
    out = []
    for bib in sorted((project / "discovery").glob("b*_*/j*_*/t*_*/runs/r*_*/result/*.bib")):
        res = bib.parent
        run, task, job, block = res.parent, res.parents[2], res.parents[3], res.parents[4]
        addr = ".".join(p.name.split("_")[0] for p in (block, job, task, run))
        rt = res / "runtime.yaml"
        st = (re.search(r"(?m)^status: (\S+)", rt.read_text(encoding="utf-8")) or [None, "?"])[1] if rt.is_file() else "?"
        for key, e in parse_bib(bib.read_text(encoding="utf-8")).items():
            out.append({"address": addr, "key": key, "doi": norm_doi(e["fields"].get("doi")), "title": e["fields"].get("title", ""),
                        "status": st, "task": ".".join(addr.split(".")[:3]), "folder": run})
    count = defaultdict(int)
    for r in out:
        count[r["address"]] += 1
    for r in out:
        r["ambiguous"] = count[r["address"]] > 1               # two Runs under one rNN: no card can name it
    return out


def signatures(secs):
    out = []
    for sec in secs:
        for f in sorted(sec.glob("runs/run-citation-*/passes/p*/result.yaml")):
            try:
                d = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
            except yaml.YAMLError:
                continue
            acc = d.get("acceptance") or {}
            checks = acc.get("checks") if isinstance(acc, dict) else acc
            human = [c for c in checks or [] if isinstance(c, dict) and "human" in str(c.get("name", ""))]
            by = str((d.get("provenance") or {}).get("verified") or "")
            signed = d.get("status") == "complete" and (by.startswith("✅") or (human and human[0].get("passed") is True))
            srcs = (d.get("payload") or {}).get("sources") or []
            out.append({"section": sec.name, "run": f.parents[2].name, "status": d.get("status"), "signed": bool(signed),
                        "by": by.split("·")[0].strip() if by.startswith("✅") else ("human check passed" if signed else ""),
                        "keys": {str(s.get("cite", "")).lstrip("@") for s in srcs if isinstance(s, dict)},
                        "dois": {norm_doi(str(s.get("identity", ""))) for s in srcs if isinstance(s, dict)} - {""}})
    return out


def card_items(secs, cm, project):
    out = []
    for sec in secs:
        f = sec / "evidence" / "cards.yaml"
        if not f.is_file():
            continue
        for ci, card in enumerate(cm.load(f)):
            if card.get("kind") != "cite":
                continue
            for ii, it in enumerate(card.get("items") or []):
                row = {"section": sec.name, "card": ci, "index": ii, "source": card.get("source"), "run": it.get("run"),
                       "for": [str(n).lstrip("S") for n in it.get("for") or []], "item": it.get("item", ""),
                       "label": it.get("label", ""), "cite": it.get("cite", ""), "need": it.get("need", ""),
                       "verified": str(it.get("verified") or ""), "key": "", "doi": "", "entry": None}
                if it.get("run") and card.get("source"):
                    try:
                        res = cm.resolve(project, "cite", f"{card['source']}.{it['run']}", f)
                        e = parse_bib(next(res.glob("*.bib")).read_text(encoding="utf-8"))
                        k, v = next(iter(e.items()))
                        row.update(key=k, doi=norm_doi(v["fields"].get("doi")), entry=v)
                    except (ValueError, StopIteration, FileNotFoundError):
                        pass
                out.append(row)
    return out


