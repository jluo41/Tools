class Paper:
    def __init__(self, j03, writing=None):
        self.j03 = Path(j03).resolve()
        self.board = pt.board_of(self.j03)
        self.project, self.root = pt.project_root(self.j03), pt.server_root(self.j03)
        groups = self.groups()
        writing = writing or next((g["writing"] for g in groups.values() if g.get("writing")), None)
        self.job = pt.writing_job(self.board, writing)
        if self.job is None:
            raise SystemExit(f"{self.board}: no writing Job (jNN_writing_v<MMDD>_<desk>)")

    def groups(self):
        out = {}
        for t in pt.tasks(self.j03):
            f = t / "scripts" / "claim_group.yaml"
            if f.is_file():
                out[t.name] = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        return out


def ledger(paper):
    secs = pt.sections(paper.job)
    cm = cards_module()
    text = {s.name: text_of(s) for s in secs}
    order = {s.name: i for i, s in enumerate(secs)}
    cites, first = defaultdict(list), {}
    for s in secs:
        for n, (sid, _, _, keys) in enumerate(text[s.name]):
            for k in keys:
                cites[k].append((s.name, sid))
                first.setdefault(k, (order[s.name], n))
    bib = {}
    for s in secs:
        for f in sorted((s / "draft" / "evidence" / "bibex").glob("*.bib")):
            for key, e in parse_bib(f.read_text(encoding="utf-8")).items():
                r = bib.setdefault(key, {"sections": [], "entry": e, "dois": defaultdict(list)})
                r["sections"].append(s.name)
                r["dois"][norm_doi(e["fields"].get("doi"))].append(s.name)
    items = card_items(secs, cm, paper.project)
    for c in items:                                         # a CITE card's Run .bib is a bib entry too (rule 1)
        if c["entry"] is not None and c["cite"] and c["cite"] not in bib:
            bib[c["cite"]] = {"sections": [c["section"]], "entry": c["entry"], "dois": defaultdict(list, {c["doi"]: [c["section"]]})}
    ref = paper.board / "delivery" / paper.job.name / "latex" / "reference.bib"
    printed_bib = set(parse_bib(ref.read_text(encoding="utf-8"))) if ref.is_file() else set()
    bank = discovery_bank(paper.project)
    sigs = signatures(secs)
    groups = {k: name for name, g in paper.groups().items() for k in g.get("keys") or []}

    def same(k, doi, key2, doi2):
        return (doi and doi == doi2) or k == key2

    rows = []
    for k in sorted(cites, key=lambda k: first[k]):
        b = bib.get(k)
        e = b["entry"]["fields"] if b else {}
        doi = norm_doi(e.get("doi"))
        dois = sorted(d for d in (b["dois"] if b else {}) if d)
        disc = [r for r in bank if same(k, doi, r["key"], r["doi"])]
        record = ("no discovery record" if not disc else "title matches"
                  if any(norm_title(r["title"]) == norm_title(e.get("title")) for r in disc) else "title differs: " + disc[0]["title"][:80])
        mine = [s for s in sigs if k in s["keys"] or (doi and doi in s["dois"])]
        cards = [c for c in items if not c["need"] and ((c["key"] and same(k, doi, c["key"], c["doi"])) or c["cite"] == k)]
        signed = [s for s in mine if s["signed"]] + [{"by": c["verified"].split("·")[0].strip(), "section": c["section"],
                                                      "run": f"{c['source']}.{c['run']}"} for c in cards if c["verified"].startswith("✅")]
        citing = sorted({s for s, _ in cites[k]}, key=order.get)
        gaps = [f"{s} {sid}" for s, sid in cites[k] if not any(c["section"] == s and sid.lstrip("S") in c["for"] for c in cards)]
        status = ("TOADD" if k == "TOADD" else "missing-bib" if not b else "verified" if signed
                  else "card-only" if cards or disc else "bib-only")
        rows.append({
            "key": k, "group": groups.get(k, ""), "status": status,
            "cited_in": "; ".join(f"{s} {', '.join(sid for t, sid in cites[k] if t == s)}" for s in citing),
            "sentences": len(cites[k]), "bib_entry": "yes" if b else "no", "bib_in": ", ".join(b["sections"]) if b else "",
            "in_reference_bib": "yes" if k in printed_bib else "no", "doi": doi,
            "doi_conflict": "; ".join(dois) if len(dois) > 1 else "",
            "title": re.sub(r"[{}]", "", e.get("title", ""))[:120], "year": e.get("year", ""), "doi_record": record,
            "verified": (f"{signed[0]['by']} · {signed[0]['section']} {signed[0]['run']}") if signed else
                        ("waiting: a Result is ready for a signature" if any(s["status"] == "ready_for_human_verification" for s in mine)
                         else "no signed Result"),
            "cite_card": "; ".join(sorted({f"{c['section']} S{','.join(c['for'])} {c['source']}.{c['run']}" for c in cards})),
            "card_gaps": "; ".join(gaps), "discovery_runs": ", ".join(sorted({r["address"] for r in disc})),
        })
    pairs = []
    for s in secs:
        lines = text[s.name]
        for (a, pa, _, ka), (b2, pb, _, kb) in zip(lines, lines[1:]):
            for k in sorted(set(ka) & set(kb)):
                pairs.append({"section": s.name, "key": k, "sentences": f"{a}, {b2}",
                              "where": "same paragraph" if pa == pb else f"across a heading ({pa} | {pb})"})
    fixes = card_fixes(paper, secs, text, rows, items, bank, groups)
    return {"sections": secs, "text": text, "rows": rows, "fixes": fixes, "pairs": pairs, "cards_mod": cm}


def fv(n):
    return int(n) if str(n).isdigit() else str(n)


def card_fixes(paper, secs, text, rows, items, bank, groups):
    """The card edits each Section needs for its printed citations (proposed, never applied here): rebind an item whose
    sentences moved, add an item from the discovery Run that holds the key, a need when none does, drop an item whose
    paper the Section no longer cites, give an item its `cite:`."""
    home = {name: str(g.get("discovery") or "") for name, g in paper.groups().items()}
    by_key = {r["key"]: r for r in rows}
    out = defaultdict(list)

    def ref(c):
        return f"evidence[{c['card']}].items[{c['index']}] · {c['source']}.{c['run']} · {c['item'] or c['label'] or '-'}"

    for sec in secs:
        s = sec.name
        mine = [c for c in items if c["section"] == s and not c["need"]]
        printed = defaultdict(list)
        for sid, _, _, keys in text[s]:
            for k in keys:
                if sid.lstrip("S") not in printed[k]:
                    printed[k].append(sid.lstrip("S"))
        used = set()
        for k, want in printed.items():
            if k == "TOADD":
                continue
            doi = by_key[k]["doi"]
            have = [c for c in mine if (c["key"] and ((doi and c["doi"] == doi) or c["key"] == k)) or c["cite"] == k]
            used.update(id(c) for c in have)
            needed = [c for c in items if c["section"] == s and c["need"] and c["cite"] == k]
            if not have and needed and set(want) <= {n for c in needed for n in c["for"]}:
                continue
            if not have:
                found = [b for b in bank if (doi and b["doi"] == doi) or b["key"] == k]
                runs = [b for b in found if not b["ambiguous"]]
                if runs:
                    b = sorted(runs, key=lambda b: (b["status"] != "complete", b["address"]))[0]
                    t, rr = b["address"].rsplit(".", 1)
                    out[s].append({"op": "add", "key": k, "sentences": [fv(n) for n in want], "card": {"kind": "cite", "source": t},
                                   "item": {"run": rr, "for": [fv(n) for n in want], "cite": k},
                                   "why": f"no card item backs {k} here; discovery Run {b['address']} holds it (key {b['key']} there)"})
                else:
                    disc = found[0]["task"] if found else home.get(groups.get(k, ""), "")
                    need = (f"renumber the Run that holds {k} in {disc}: two Runs share its number" if found else
                            f"a discovery Run for {k}" + (f" (doi {doi})" if doi else " (no DOI: a web or book source)"))
                    item = {"need": need, "for": [fv(n) for n in want], "cite": k}
                    if disc:
                        item["propose"] = {"level": "run", "in": disc}
                    out[s].append({"op": "need", "key": k, "sentences": [fv(n) for n in want],
                                   "card": {"kind": "cite", "source": disc}, "item": item,
                                   "why": "no discovery Run holds this source" if not found else "its discovery Run's address names two Runs"})
                continue
            missing = [n for n in want if not any(n in c["for"] for c in have)]
            plan = {id(c): [n for n in c["for"] if n in want] for c in have}
            for c in have:
                if not plan[id(c)]:
                    plan[id(c)], missing = (list(missing), []) if missing else (None, [])
            if missing:
                first = next(c for c in have if plan[id(c)])
                plan[id(first)] = sorted(set(plan[id(first)]) | set(missing), key=str)
            for c in have:
                new = plan[id(c)]
                if new is None:
                    out[s].append({"op": "drop", "key": k, "item": ref(c), "from": {"for": [fv(n) for n in c["for"]]},
                                   "why": f"a duplicate: another item of the same Run already backs {k} here"})
                elif new != c["for"]:
                    out[s].append({"op": "rebind", "key": k, "item": ref(c),
                                   "from": {"for": [fv(n) for n in c["for"]], "cite": c["cite"] or None},
                                   "to": {"for": [fv(n) for n in new], "cite": k},
                                   "why": f"{k} is cited at {', '.join(want)}; the item named {', '.join(c['for']) or 'none'}"})
                elif c["cite"] != k:
                    out[s].append({"op": "cite-field", "key": k, "item": ref(c), "to": {"cite": k},
                                   "why": "the item has no `cite:`; cards.py bib finds a printed key's Run by it"})
        for c in mine:
            if id(c) in used or not c["key"]:
                continue
            out[s].append({"op": "drop", "key": c["cite"] or c["key"], "item": ref(c), "from": {"for": [fv(n) for n in c["for"]]},
                           "why": f"{c['cite'] or c['key']} is not cited in this Section's printed text"})
    return dict(out)


class NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def dump(data):
    return yaml.dump(data, Dumper=NoAliases, sort_keys=False, allow_unicode=True, width=120)


def headline(rows, pairs):
    c = {s: sum(r["status"] == s for r in rows) for s in STATUSES}
    gaps = sum(len([g for g in r["card_gaps"].split("; ") if g]) for r in rows)
    line = (f"{len(rows)} keys: " + ", ".join(f"{c[s]} {s}" for s in STATUSES) + f"; {sum(not r['doi'] for r in rows)} without a DOI"
            + f"; {len(pairs)} back-to-back pairs; {gaps} citing sentences without a CITE card")
    return line, c, gaps


# ── a Run ───────────────────────────────────────────────────────────────────────────────────────────────────────────
def run(task, out):
    task, out = Path(task).resolve(), Path(out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    paper = Paper(task.parent)
    L = ledger(paper)
    group = paper.groups().get(task.name)
    keys = None if task.name == CHECK_TASK or group is None else set(group.get("keys") or [])
    rows = [r for r in L["rows"] if keys is None or r["key"] in keys]
    pairs = [p for p in L["pairs"] if keys is None or p["key"] in keys]
    fixes = {s: [o for o in ops if keys is None or o["key"] in keys] for s, ops in L["fixes"].items()}
    fixes = {s: ops for s, ops in fixes.items() if ops}
    line, c, gaps = headline(rows, pairs)
    ungrouped = [r["key"] for r in L["rows"] if not r["group"] and r["key"] != "TOADD"] if keys is None else []
    if ungrouped:
        line += f"; {len(ungrouped)} printed keys in no claim group"
    with (out / "citations.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]) if rows else ["key"])
        w.writeheader()
        w.writerows(rows)
    (out / "headline.txt").write_text(f"{task.name}: {line}\n", encoding="utf-8")
    doc = {"task": task.name, "writing": paper.job.name, "keys": [r["key"] for r in rows],
           "counts": {"keys": len(rows), **c, "no doi": sum(not r["doi"] for r in rows), "back-to-back": len(pairs),
                      "sentences without a card": gaps, "card edits": sum(len(v) for v in fixes.values())},
           "headline": line, "ungrouped": ungrouped,
           "citations": [{k: r[k] for k in ("key", "group", "status", "cited_in", "doi", "verified", "cite_card", "card_gaps",
                                             "discovery_runs")} for r in rows],
           "back_to_back": pairs, "card_fixes": fixes}
    (out / "values.yaml").write_text(GEN.replace("gen;", "run;") + dump(doc), encoding="utf-8")
    write_html(out, task.name, line, rows, pairs, paper)
    if keys is None:
        write_check(out, paper, L, rows, pairs, fixes, ungrouped)
    print(f"{task.name}: {line}")


def write_html(out, task, line, rows, pairs, paper):
    """citations.html: one row per key, problems first; names link to their Section and discovery Run."""
    order = {s: i for i, s in enumerate(("TOADD", "missing-bib", "bib-only", "card-only", "verified"))}

    def sections(text):
        def one(m):
            f = paper.job / m.group(0)
            return f'<a target=_top href="{esc(pt.href(f, paper.root, "&section=work&group=write"))}">{m.group(0)}</a>' if f.is_dir() else m.group(0)
        return re.sub(r"\bt\d\d_[a-z][a-z0-9_-]*", one, text)

    def runs(text):
        def one(m):
            f = pt.find_run(paper.project, m.group(0))
            return f'<a target=_top href="{esc(pt.href(f, paper.root))}">{m.group(0)}</a>' if f else m.group(0)
