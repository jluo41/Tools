def apply(j03, writing=None):
    """Write the proposed CITE card edits into each printed Section's evidence/cards.yaml; VALUE items are kept."""
    paper = Paper(j03, writing)
    L = ledger(paper)
    for s, ops in L["fixes"].items():
        f = paper.job / s / "evidence" / "cards.yaml"
        text = f.read_text(encoding="utf-8") if f.is_file() else "evidence: []\n"
        head = "".join(ln + "\n" for ln in text.splitlines() if ln.startswith("#")) if text.startswith("#") else ""
        doc = yaml.safe_load(text) or {"evidence": []}
        ev = doc.setdefault("evidence", [])
        before = [c for c in ev if c.get("kind") in ("value", "work")]
        touched, drops, n = {}, set(), defaultdict(int)
        for o in ops:
            if o["op"] in ("rebind", "cite-field", "drop"):
                m = re.match(r"evidence\[(\d+)\]\.items\[(\d+)\]", o["item"])
                ci, ii = int(m[1]), int(m[2])
                if (ci, ii) in touched:
                    raise SystemExit(f"{s}: evidence[{ci}].items[{ii}] has two edits ({touched[(ci, ii)]}, {o['op']} {o['key']})")
                touched[(ci, ii)] = f"{o['op']} {o['key']}"
                if o["op"] == "drop":
                    drops.add((ci, ii))
                else:
                    it = ev[ci]["items"][ii]
                    if o["op"] == "rebind":
                        it["for"] = o["to"]["for"]
                    it["cite"] = o["to"]["cite"]
            else:
                card = next((c for c in ev if c.get("kind") == "cite" and c.get("source") == o["card"]["source"]), None)
                if card is None:
                    card = {"kind": "cite", "items": []}
                    if o["card"]["source"]:
                        card["source"] = o["card"]["source"]
                    ev.append(card)
                card["items"].append(dict(o["item"]))
            n[o["op"]] += 1
        for ci, card in enumerate(ev):
            card["items"] = [it for ii, it in enumerate(card.get("items") or []) if (ci, ii) not in drops]
        doc["evidence"] = [c for c in ev if c.get("items")]
        if [c for c in doc["evidence"] if c.get("kind") in ("value", "work")] != before:
            raise SystemExit(f"{s}: a VALUE card changed; nothing written")
        f.parent.mkdir(parents=True, exist_ok=True)
        stamp = f"# {date.today().strftime('%y%m%d')}: CITE items edited by cite_tasks.py apply (j03 t99); VALUE items untouched.\n"
        f.write_text(head + (stamp if stamp not in head else "") + dump(doc), encoding="utf-8")
        print(f"{s}: " + ", ".join(f"{v} {k}" for k, v in n.items()))


def inventory(j03, writing=None):
    for r in ledger(Paper(j03, writing))["rows"]:
        print(f"{r['key']:26} {r['group'] or '-':40} {r['status']:12} {r['year']:5} {r['title'][:50]} | {r['cited_in'][:60]}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("cmd", choices=["gen", "run", "apply", "inventory"])
    ap.add_argument("path", type=Path, help="the j03_evidence_cite Job (run: a claim Task)")
    ap.add_argument("out", type=Path, nargs="?", help="run: the result dir")
    ap.add_argument("--writing", help="the writing Job (default: the Board's newest)")
    ap.add_argument("--started-by", default="cite_tasks.py gen: the citation Job's Runs, made from its claim groups")
    a = ap.parse_args(argv)
    if a.cmd == "run":
        if a.out is None:
            ap.error("run needs <claim Task> <result dir>")
        run(a.path, a.out)
    elif a.cmd == "gen":
        gen(a.path, a.writing, a.started_by)
    elif a.cmd == "apply":
        apply(a.path, a.writing)
    else:
        inventory(a.path, a.writing)


if __name__ == "__main__":
    main()
