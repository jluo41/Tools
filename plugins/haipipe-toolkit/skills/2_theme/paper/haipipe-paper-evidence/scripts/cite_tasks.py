def write_check(out, paper, L, rows, pairs, fixes, ungrouped):
    """The paper-wide Task: checks.md, proposed-cards/<section>.yaml, proposals/<section>.md."""
    cm = L["cards_mod"]
    lines = [f"# Paper citation check · {paper.job.name}", "",
             f"Written by cite_tasks.py run on {date.today().isoformat()}; read only. A card edit below is proposed, "
             "never applied: `cite_tasks.py apply` (run by a person) writes it.", "", "## cards.py check, per printed Section", ""]
    for sec in L["sections"]:
        f = sec / "evidence" / "cards.yaml"
        if not f.is_file():
            lines.append(f"- `{sec.name}`: no evidence/cards.yaml")
            continue
        probs = cm.check(cm.load(f), paper.project, pt.index(sec), near=f)
        lines.append(f"- `{sec.name}`: " + ("every address, fact, value and anchor resolves" if not probs else f"{len(probs)} problems"))
        lines += [f"  - {p}" for p in probs]
    lines += ["", "## Keys to look at", ""]
    for st in ("TOADD", "missing-bib"):
        hit = [r for r in rows if r["status"] == st]
        lines.append(f"- {st}: " + (", ".join(f"`{r['key']}` ({r['cited_in']})" for r in hit) if hit else "none"))
    lines.append("- no DOI: " + (", ".join(f"`{r['key']}`" for r in rows if not r["doi"] and r["bib_entry"] == "yes") or "none"))
    lines.append("- one key, two DOIs: " + (", ".join(f"`{r['key']}` ({r['doi_conflict']})" for r in rows if r["doi_conflict"]) or "none"))
    lines.append("- in no claim group: " + (", ".join(f"`{k}`" for k in ungrouped) or "none"))
    lines += ["", "## Back-to-back sentences citing the same key", ""]
    lines += [f"- `{p['section']}` {p['sentences']} · `{p['key']}` · {p['where']}" for p in pairs] or ["- none"]
    lines += ["", "## Card edits, per Section (proposed-cards/<section>.yaml)", ""]
    for s, ops in fixes.items():
        n = defaultdict(int)
        for o in ops:
            n[o["op"]] += 1
        lines.append(f"- `{s}`: " + ", ".join(f"{v} {k}" for k, v in n.items()))
        (out / "proposed-cards").mkdir(exist_ok=True)
        (out / "proposed-cards" / f"{s}.yaml").write_text(
            f"# Proposed edits to {paper.job.name}/{s}/evidence/cards.yaml (CITE only), written by cite_tasks.py run. "
            "Not applied.\n" + dump({"section": s, "edits": ops}), encoding="utf-8")
        needs = [{"kind": "cite", "source": o["card"]["source"], "items": [o["item"]]} for o in ops if o["op"] == "need"]
        f = paper.job / s / "evidence" / "cards.yaml"
        props = cm.proposals((cm.load(f) if f.is_file() else []) + needs, s)
        if props:
            (out / "proposals").mkdir(exist_ok=True)
            (out / "proposals" / f"{s}.md").write_text(
                "Evidence proposals (cards.py proposals over the Section's cards plus this Run's proposed needs)\n\n"
                + "\n".join(f"- [ ] {ln} <!-- {pid} -->" for pid, ln in props) + "\n", encoding="utf-8")
    (out / "checks.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


