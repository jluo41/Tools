"""messages.py: a Block's kept and released messages, with and without the method, a name per message, the length
check; release.words_of takes the fenced message out of a face's ## Design."""
from __future__ import annotations

import io
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
import messages as M  # noqa: E402
import release as R  # noqa: E402


def _job(block: Path, jid: str, method: str, designs: list) -> None:
    job = block / f"{jid}_g01_{method.split()[0].lower()}"
    job.mkdir(parents=True)
    (job / f"{job.name}.md").write_text(f"---\ngoal: G01\nmethod: {method}\ninputs: i1\nstate: open\n---\n\n# {jid}\n")
    for k, (name, state, design) in enumerate(designs, 1):
        t = job / f"t0{k}_d0{k}_{name}"
        t.mkdir()
        (t / f"{t.name}.md").write_text(f"---\nstate: {state}\nname: {name}\n---\n\n# d0{k}\n\n## Design\n\n{design}\n\n"
                                        "## Evaluation\n\nT0 ✓\n", encoding="utf-8")


class MessagesTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.block = Path(self.tmp.name) / "Design-demo"
        _job(self.block, "j01", "M01 m2", [("plain", "released", "Hi, {NAME}. Review: {LINK} Reply STOP"),
                                          ("gone", "dropped", "never shown")])
        _job(self.block, "j02", "M04 m3", [("plain", "kept", "```text\nLine one\n{NAME}: {LINK} Reply STOP\n```\n\n"
                                                             "Characters: 30 of 140 (a note, not the message)."),
                                          ("long", "kept", "x" * 141)])

    def tearDown(self):
        self.tmp.cleanup()

    def test_words_of_keeps_only_the_fenced_message(self):
        self.assertEqual(R.words_of("```text\nHi {LINK}\n```\n\nCharacters: 9"), "Hi {LINK}")
        self.assertEqual(R.words_of("Hi {LINK}"), "Hi {LINK}")

    def test_kept_and_released_only_with_unique_names_and_lengths(self):
        rows = M.messages(self.block, "{LINK}")
        self.assertEqual([r["name"] for r in rows], ["plain", "plain-d01", "long"])
        self.assertEqual(rows[1]["words"], "Line one\n{NAME}: {LINK} Reply STOP")
        self.assertEqual(rows[1]["length"], len("Line one\n{NAME}:  Reply STOP"))
        self.assertTrue(rows[0]["method"].startswith("M01"))

    def test_two_versions_numbered_with_the_control_as_message_0(self):
        (self.block / "delivery").mkdir()
        (self.block / "delivery" / "messages-with-method.md").write_text(
            "# Messages by method · old\n\nGenerated by haipipe-design-delivery `scripts/messages.py`\n")
        task = Path(self.tmp.name) / "task.md"
        task.write_text("# Task\n\n## Sent today\n\nHi {NAME}, review: {LINK} Reply STOP\n", encoding="utf-8")
        with redirect_stdout(io.StringIO()):
            outs = M.main([str(self.block), "--control-file", str(task), "--control-heading", "Sent today",
                           "--control-name", "default"])
        self.assertEqual([p.name for p in outs], ["messages-version-1.md", "messages-version-2.md"])
        self.assertFalse((self.block / "delivery" / "messages-with-method.md").exists())
        v1, v2 = (p.read_text(encoding="utf-8") for p in outs)
        for text in (v1, v2):
            self.assertIn("## Length check", text)
            self.assertIn("1 over the limit as written", text)
            self.assertIn("Line one ⏎ {NAME}", text)
            self.assertNotIn("Characters: 30", text)
            self.assertNotIn("never shown", text)
        self.assertIn("| 0 | control: sent today | default | Hi {NAME}, review: {LINK} Reply STOP |", v1)
        first = [l for l in v2.splitlines() if l.startswith("| ")][1]   # [0] is the header row
        self.assertTrue(first.startswith("| 0 | default |"), first)
        n = {l.split(" | ")[1]: l.split(" | ")[0][2:] for l in v2.splitlines()[8:12] if l.startswith("| ")}
        for name, k in n.items():                               # one number per message, the same in both files
            self.assertRegex(v1, rf"\| {k} \| [^|]+ \| {name} \|")
        self.assertNotIn("M01", v2)
        self.assertNotIn("M04", v2)

    def test_order_is_random_but_fixed_by_the_seed(self):
        rows = lambda: M.messages(self.block, "{LINK}")                    # noqa: E731
        by = lambda rs: [r["name"] for r in sorted(rs, key=lambda r: r["n"])]  # noqa: E731
        self.assertEqual(by(M.number(rows(), "random", 1)), by(M.number(rows(), "random", 1)))
        self.assertEqual(by(M.number(rows(), "name")), ["long", "plain", "plain-d01"])
        orders = {tuple(by(M.number(rows(), "random", s))) for s in range(1, 12)}
        self.assertGreater(len(orders), 1)                                  # the seed changes the order

    def test_carried_messages_follow_the_designs_and_never_renumber_them(self):
        carry = Path(self.tmp.name) / "carried.md"
        carry.write_text("# Carried\n\nnote\n\n## winnerA\n\n```\nOld winner A {LINK}\n```\n\nevidence line\n\n"
                         "## winnerB\n\nOld winner B {LINK}\n", encoding="utf-8")
        before = {r["name"]: r["n"] for r in M.number(M.messages(self.block, "{LINK}"))}
        with redirect_stdout(io.StringIO()):
            outs = M.main([str(self.block), "--carry-file", str(carry)])
        v1, v2 = (p.read_text(encoding="utf-8") for p in outs)
        for name, k in before.items():                          # the new designs keep their numbers
            self.assertRegex(v2, rf"\| {k} \| {name} \|")
        k = len(before)
        self.assertIn(f"| {k + 1} | winnerA | Old winner A {{LINK}} |", v2)
        self.assertIn(f"| {k + 2} | winnerB | Old winner B {{LINK}} |", v2)
        self.assertIn(f"2 carried over word for word from earlier experiments (#{k + 1} to #{k + 2})", v2)
        self.assertIn("carried over: an earlier experiment's winner | winnerA", v1)
        self.assertNotIn("evidence line", v2)

    def test_no_control_without_its_heading(self):
        with self.assertRaises(SystemExit), redirect_stdout(io.StringIO()):
            M.main([str(self.block), "--control-file", str(Path(self.tmp.name) / "task.md")])


if __name__ == "__main__":
    unittest.main()
