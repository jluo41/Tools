"""A design Block's message lists: every Job's kept or released designs, word for word, as two files in delivery/.

    python messages.py <block folder> [--control-file <md> --control-heading "<heading>" [--control-name control]]
                       [--order random|name] [--seed 1] [--limit 140] [--placeholder "{NAME}"] [--link "{LINK}"]
                       [--dry]

Reads each Job's face (its method pin) and its design Tasks whose state is `kept` or `released`, the words in each
face's ## Design (a fenced block there is the message; a note around it is not). With --control-file, the message under
--control-heading in that file (the text sent today) is message 0, the control every other message is read against.
Writes `messages-version-1.md` (# · method · name · content · length, in method order) and `messages-version-2.md`
(# · name · content · length, in number order, so neither the columns nor the order tell the method); each ends with a
length check, tightest first. A message's number is the same in both files: 0 the control, then 1, 2 … in a random
order fixed by --seed (each message's place comes from a hash of the seed and its name, so a rerun gives the same
order), or in name order with --order name.
A name is the design Task's name; a name two Jobs share takes its design id (`-d13`) after its first use. Length counts
what the reader gets except the link placeholder; a line break is one. The length check gives each message's room for
the filled-in placeholder: the limit minus the length, plus the placeholder's own characters. Generated: rerun after a
release or a swap; the files are never edited by hand. This script's older files (`messages.md`,
`messages-with-method.md`, `messages-without-method.md`) are removed. Prints what it wrote.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from release import DESIGN, front, section, words_of  # noqa: E402
from summary import method_name  # noqa: E402

JOB = re.compile(r"^j\d+_")
SHOWN = ("kept", "released")


def messages(block: Path, link: str) -> list:
    rows, seen = [], set()
    for job in sorted(p for p in block.iterdir() if p.is_dir() and JOB.match(p.name)):
        pin = str(front(job / f"{job.name}.md").get("method", ""))
        if not pin:
            continue
        method = f"{pin.split()[0]} {method_name(pin)}".strip()
        for t in sorted(p for p in job.iterdir() if p.is_dir() and DESIGN.match(p.name)):
            face = t / f"{t.name}.md"
            fm = front(face)
            if str(fm.get("state", "")) not in SHOWN:
                continue
            words = words_of(section(face, "Design"))
            design, slug = DESIGN.match(t.name).groups()
            name = str(fm.get("name") or slug)
            if name in seen:
                name = f"{name}-{design}"
            seen.add(name)
            rows.append({"job": job.name.split("_", 1)[0], "method": method, "name": name, "words": words,
                         "state": str(fm["state"]), "length": len(words.replace(link, ""))})
    return rows


def control(path: Path, heading: str, name: str, link: str) -> dict:
    words = words_of(section(path, re.escape(heading)))
    if not words:
        sys.exit(f"{path.name} has no ## {heading} with a message under it")
    return {"job": "", "method": "control: sent today", "name": name, "words": words, "state": "control",
            "length": len(words.replace(link, ""))}


def number(rows: list, order: str = "random", seed: int = 1) -> list:
    """The same number in both files: the control 0, then 1, 2 … in a seeded random order, or in name order."""
    if order == "name":
        key = lambda r: r["name"]                                                   # noqa: E731
    else:
        key = lambda r: hashlib.sha256(f"{seed}:{r['name']}".encode()).hexdigest()  # noqa: E731
    rest = sorted((r for r in rows if r["state"] != "control"), key=key)
    for k, r in enumerate(rest, 1):
        r["n"] = k
    for r in rows:
        r.setdefault("n", 0)
    return rows


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ⏎ ")


def page(block: Path, rows: list, limit: int, placeholder: str, link: str, with_method: bool) -> str:
    designs = [r for r in rows if r["state"] != "control"]
    over = [r for r in rows if r["length"] > limit]
    room = lambda r: limit - r["length"] + len(placeholder)                       # noqa: E731
    order = rows if with_method else sorted(rows, key=lambda r: r["n"])
    lead = (f"Generated by haipipe-design-delivery `scripts/messages.py`; rerun it after a release or a swap, never "
            f"edit this file. {len(designs)} messages"
            + (", and message 0, the control: the text sent today." if len(rows) > len(designs) else "."))
    if with_method:
        states = {}
        for r in designs:
            states.setdefault(r["method"], set()).add(r["state"])
        lead += " " + "; ".join(f"{m}: {'/'.join(sorted(st))}" for m, st in states.items()) + "."
    lines = [f"# Messages{' by method' if with_method else ''} · {block.name}", "", lead, "",
             f"A message's number (#) is the same in both versions. Length counts every character except `{link}`, "
             f"with `{placeholder}` as its {len(placeholder)} written characters and a line break (⏎) as one. "
             f"Limit: {limit}. " + (f"{len(over)} over the limit as written." if over else "All within the limit as written."),
             ""]
    if with_method:
        lines += ["| # | method | name | content | length |", "|---|---|---|---|---|"]
        lines += [f"| {r['n']} | {r['method']} | {r['name']} | {cell(r['words'])} | {r['length']} |" for r in order]
    else:
        lines += ["| # | name | content | length |", "|---|---|---|---|"]
        lines += [f"| {r['n']} | {r['name']} | {cell(r['words'])} | {r['length']} |" for r in order]
    lines += ["", "## Length check", "",
              f"Room for the filled-in `{placeholder}`: the longest it can be before the message passes {limit}. "
              "Tightest first.", ""]
    tight = sorted(rows, key=lambda r: (room(r), r["n"]))
    if with_method:
        lines += ["| # | method | name | length | room for the name |", "|---|---|---|---|---|"]
        lines += [f"| {r['n']} | {r['method']} | {r['name']} | {r['length']} | {room(r)} |" for r in tight]
    else:
        lines += ["| # | name | length | room for the name |", "|---|---|---|---|"]
        lines += [f"| {r['n']} | {r['name']} | {r['length']} | {room(r)} |" for r in tight]
    return "\n".join(lines) + "\n"


def main(argv=None) -> list:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("block", type=Path)
    ap.add_argument("--limit", type=int, default=140)
    ap.add_argument("--placeholder", default="{NAME}")
    ap.add_argument("--link", default="{LINK}")
    ap.add_argument("--control-file", type=Path)
    ap.add_argument("--control-heading", default="")
    ap.add_argument("--control-name", default="control")
    ap.add_argument("--order", choices=("random", "name"), default="random")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--dry", action="store_true")
    a = ap.parse_args(argv)
    rows = messages(a.block, a.link)
    if not rows:
        sys.exit(f"{a.block.name}: no kept or released design in any Job")
    if a.control_file:
        if not a.control_heading:
            sys.exit("--control-file needs --control-heading: the heading the control message sits under")
        rows = [control(a.control_file, a.control_heading, a.control_name, a.link)] + rows
    rows = number(rows, a.order, a.seed)
    delivery = a.block / "delivery"
    outs = {delivery / "messages-version-1.md": page(a.block, rows, a.limit, a.placeholder, a.link, True),
            delivery / "messages-version-2.md": page(a.block, rows, a.limit, a.placeholder, a.link, False)}
    if a.dry:
        for text in outs.values():
            print(text)
        return list(outs)
    delivery.mkdir(parents=True, exist_ok=True)
    for path, text in outs.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path} ({len(rows)} messages)")
    for name in ("messages.md", "messages-with-method.md", "messages-without-method.md"):   # this script's older files
        old = delivery / name
        if old.is_file() and old.read_text(encoding="utf-8").startswith("# Messages") and \
                "scripts/messages.py" in old.read_text(encoding="utf-8"):
            old.unlink()
            print(f"removed {old} (now messages-version-1.md and -2.md)")
    return list(outs)


if __name__ == "__main__":
    main()
